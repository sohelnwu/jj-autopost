const REEL_TAGS = ['reels', 'fbreels', 'viralreels'];

export function hashtags(page, topic, { reel = false, extra = [] } = {}) {
  const set = [...(page.hashtags || []), ...(TOPIC_TAGS[topic] || []), ...extra, ...(reel ? REEL_TAGS : [])];
  const seen = new Set();
  return set.map((h) => h.replace(/^#/, '').replace(/\s+/g, ''))
    .filter((h) => h && !seen.has(h.toLowerCase()) && seen.add(h.toLowerCase()))
    .slice(0, 9).map((h) => `#${h}`).join(' ');
}

